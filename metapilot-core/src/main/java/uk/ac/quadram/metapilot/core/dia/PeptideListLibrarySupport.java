package uk.ac.quadram.metapilot.core.dia;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileReader;
import java.io.IOException;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.TreeSet;

import uk.ac.quadram.metapilot.dbSearch.diann.DiannParameter;

/**
 * Spectral library from a peptide list (for example the final peptides of a DDA search): the peptides are written as
 * one FASTA entry each and DIA-NN predicts the library from that FASTA.
 *
 * <p>DIA-NN treats every FASTA entry as a protein, so settings meant for proteins act on each peptide here:
 * <ul>
 *   <li>protein N-terminal acetylation ({@code UniMod:1 *n}) would add an acetylated form of every peptide, and
 *   N-terminal methionine excision a Met-less form of every peptide starting with M. Neither was observed, so both are
 *   switched off; residue modifications (Met oxidation, phospho, GG) stay as set;</li>
 *   <li>DIA-NN digests each entry again: a peptide with more internal cleavage sites than the allowed missed cleavages
 *   is split and its full sequence is lost. The missed cleavages are therefore raised to the most found in the list,
 *   up to {@link #MAX_LIBRARY_MISSED_CLEAVAGES} (the DDA searches allow 2). Sub-peptides of an entry are still
 *   generated by the digestion.</li>
 * </ul>
 * Peptides are written in sorted order, so the FASTA (entry names {@code pro0, pro1, ...}) is the same for the same
 * peptide list.
 */
public final class PeptideListLibrarySupport {

	/** Missed cleavages kept intact at most; the MetaPilot DDA searches allow 2. */
	public static final int MAX_LIBRARY_MISSED_CLEAVAGES = 2;

	private PeptideListLibrarySupport() {
	}

	/** Unique unmodified peptide sequences, sorted, with the properties that matter for the library build. */
	public static final class PeptideList {
		public final List<String> peptides;
		public final int maxInternalCleavageSites;
		public final int minLength;
		public final int maxLength;

		PeptideList(List<String> peptides) {
			this.peptides = Collections.unmodifiableList(peptides);
			int maxSites = 0;
			int minLen = Integer.MAX_VALUE;
			int maxLen = 0;
			for (String p : peptides) {
				maxSites = Math.max(maxSites, internalCleavageSites(p));
				minLen = Math.min(minLen, p.length());
				maxLen = Math.max(maxLen, p.length());
			}
			this.maxInternalCleavageSites = maxSites;
			this.minLength = peptides.isEmpty() ? 0 : minLen;
			this.maxLength = maxLen;
		}

		/** Peptides with more internal cleavage sites than {@code missed} (split by DIA-NN). */
		public int countWithMoreSitesThan(int missed) {
			int n = 0;
			for (String p : peptides) {
				if (internalCleavageSites(p) > missed) n++;
			}
			return n;
		}

		/** Peptides outside the DIA-NN length range (not in the library). */
		public int countOutsideLength(int minLen, int maxLen) {
			int n = 0;
			for (String p : peptides) {
				if (p.length() < minLen || p.length() > maxLen) n++;
			}
			return n;
		}
	}

	/**
	 * Internal tryptic cleavage sites of a peptide for DIA-NN's {@code --cut K*,R*} (Trypsin/P): K or R anywhere but at
	 * the C-terminus.
	 */
	public static int internalCleavageSites(String peptide) {
		int n = 0;
		for (int i = 0; i < peptide.length() - 1; i++) {
			char c = peptide.charAt(i);
			if (c == 'K' || c == 'R') n++;
		}
		return n;
	}

	/**
	 * Reads a peptide table (tab-separated, with a "Base sequence" or else a "Sequence" column). Modification
	 * annotations in () or [] are removed; rows with unbalanced brackets are skipped, as before.
	 */
	public static PeptideList readPeptideTable(File table) throws IOException {
		TreeSet<String> peps = new TreeSet<>();
		try (BufferedReader reader = new BufferedReader(new FileReader(table))) {
			String header = reader.readLine();
			if (header == null) throw new IOException("Empty peptide table: " + table.getAbsolutePath());
			String[] title = header.split("\t");
			int seqCol = -1;
			int baseCol = -1;
			for (int i = 0; i < title.length; i++) {
				if (title[i].equals("Base sequence")) baseCol = i;
				else if (title[i].equals("Sequence")) seqCol = i;
			}
			int col = baseCol >= 0 ? baseCol : seqCol;
			if (col < 0) {
				throw new IOException("Peptide table has no \"Base sequence\" or \"Sequence\" column: " + table.getAbsolutePath());
			}
			String line;
			while ((line = reader.readLine()) != null) {
				String[] cs = line.split("\t");
				if (cs.length <= col) continue;
				String seq = stripModifications(cs[col]);
				if (seq != null && !seq.isEmpty()) peps.add(seq);
			}
		}
		return new PeptideList(new ArrayList<>(peps));
	}

	/** Reads the peptides back from a peptide FASTA written by {@link #writePeptideFasta}. */
	public static PeptideList readPeptideFasta(File fasta) throws IOException {
		TreeSet<String> peps = new TreeSet<>();
		try (BufferedReader reader = new BufferedReader(new FileReader(fasta))) {
			String line;
			while ((line = reader.readLine()) != null) {
				line = line.trim();
				if (!line.isEmpty() && !line.startsWith(">")) peps.add(line);
			}
		}
		return new PeptideList(new ArrayList<>(peps));
	}

	/** Uppercase residues outside () / [] annotations; null when the brackets do not balance. */
	static String stripModifications(String annotated) {
		int open = 0;
		int close = 0;
		boolean inside = false;
		StringBuilder sb = new StringBuilder();
		for (int i = 0; i < annotated.length(); i++) {
			char aa = annotated.charAt(i);
			if (aa == '(' || aa == '[') {
				inside = true;
				open++;
			} else if (aa == ')' || aa == ']') {
				inside = false;
				close++;
			} else if (!inside && aa >= 'A' && aa <= 'Z') {
				sb.append(aa);
			}
		}
		return open == close ? sb.toString() : null;
	}

	/** One entry per peptide, in sorted order: {@code >proN proN} / sequence. */
	public static void writePeptideFasta(PeptideList list, File fasta) throws IOException {
		try (PrintWriter writer = new PrintWriter(fasta)) {
			for (int i = 0; i < list.peptides.size(); i++) {
				writer.println(">pro" + i + " pro" + i);
				writer.println(list.peptides.get(i));
			}
		}
	}

	/**
	 * Switches off the protein N-terminal rules (acetylation {@code UniMod:1 *n}, N-terminal Met excision) for a
	 * library built from peptide entries. Used for the peptide-level databases of the Deep workflows (final
	 * combined.fasta from the round peptides) and peptide-based rounds.
	 */
	public static void applyPeptideEntryRules(DiannParameter diannPar) {
		diannPar.setAcety_proN(false);
		diannPar.setM_excision(false);
	}

	/** A library build step that may throw. */
	@FunctionalInterface
	public interface BuildStep {
		void run() throws Exception;
	}

	/**
	 * Runs {@code build} with the peptide-entry rules on {@code diannPar} and restores the previous protein
	 * N-terminal settings afterwards, for callers that reuse one DiannParameter for later searches.
	 */
	public static void withPeptideEntryRules(DiannParameter diannPar, BuildStep build) throws Exception {
		boolean acetyl = diannPar.isAcety_proN();
		boolean excision = diannPar.isM_excision();
		applyPeptideEntryRules(diannPar);
		try {
			build.run();
		} finally {
			diannPar.setAcety_proN(acetyl);
			diannPar.setM_excision(excision);
		}
	}

	/** {@link #withPeptideEntryRules(DiannParameter, BuildStep)} for build steps that do not throw. */
	public static void runWithPeptideEntryRules(DiannParameter diannPar, Runnable build) {
		boolean acetyl = diannPar.isAcety_proN();
		boolean excision = diannPar.isM_excision();
		applyPeptideEntryRules(diannPar);
		try {
			build.run();
		} finally {
			diannPar.setAcety_proN(acetyl);
			diannPar.setM_excision(excision);
		}
	}

	/**
	 * Sets the DIA-NN library rules for a peptide FASTA: protein N-terminal acetylation and N-terminal methionine
	 * excision off, missed cleavages = max(requested, most internal sites in the list, capped at
	 * {@link #MAX_LIBRARY_MISSED_CLEAVAGES}).
	 *
	 * @return the missed cleavages used
	 */
	public static int configureForPeptideLibrary(DiannParameter diannPar, int requestedMissedCleavages, PeptideList list) {
		applyPeptideEntryRules(diannPar);
		int missed = Math.max(requestedMissedCleavages,
				Math.min(list.maxInternalCleavageSites, MAX_LIBRARY_MISSED_CLEAVAGES));
		diannPar.setMissed_cleavages(missed);
		return missed;
	}

	/** Lines for the library's _info.txt and the log, describing what went into the library. */
	public static List<String> describe(PeptideList list, DiannParameter diannPar) {
		List<String> lines = new ArrayList<>();
		int missed = diannPar.getMissed_cleavages();
		lines.add("Library source:\tpeptide list");
		lines.add("Peptides in list:\t" + list.peptides.size());
		lines.add("Peptide length range:\t" + list.minLength + "-" + list.maxLength);
		lines.add("Peptides outside length " + diannPar.getMin_pep_len() + "-" + diannPar.getMax_pep_len() + ":\t"
				+ list.countOutsideLength(diannPar.getMin_pep_len(), diannPar.getMax_pep_len()));
		lines.add("Peptides with more than " + missed + " internal cleavage sites (split):\t"
				+ list.countWithMoreSitesThan(missed));
		lines.add("Protein N-terminal acetylation:\toff (peptide entries)");
		lines.add("N-terminal Met excision:\toff (peptide entries)");
		return lines;
	}
}
