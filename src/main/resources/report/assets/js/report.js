const manifestFromWindow = typeof window !== 'undefined' ? window.METAPILOT_MANIFEST : null;
const hasInlineManifest = manifestFromWindow && Array.isArray(manifestFromWindow.reports);
const manifestUrls = ["reports/manifest.json", "generate_manifest.php"];
const listContainer = document.querySelector('[data-report-list]');
const statusMessage = document.querySelector('[data-status-message]');
const updatedAtEl = document.querySelector('[data-updated-at]');

const formatDate = (isoString) => {
    if (!isoString) {
        return "Unknown";
    }
    try {
        const date = new Date(isoString);
        return new Intl.DateTimeFormat(undefined, {
            dateStyle: "medium",
            timeStyle: "short"
        }).format(date);
    } catch (_err) {
        return isoString;
    }
};

const buildHref = (report) => {
    const file = report.file ?? '';
    if (!file) {
        return '#';
    }
    if (/^https?:/i.test(file)) {
        return file;
    }
    if (file.startsWith('reports/')) {
        return file;
    }
    if (report.folder && report.folder !== '.' && report.folder !== '') {
        return `reports/${report.folder}/${file}`;
    }
    return `reports/${file}`;
};

const renderReports = (reports) => {
    if (!Array.isArray(reports) || reports.length === 0) {
        statusMessage?.classList.replace("alert-info", "alert-warning");
        statusMessage.textContent = "No reports have been generated yet.";
        return;
    }

    if (statusMessage) {
        statusMessage.remove();
    }

    if (listContainer) {
        listContainer.hidden = false;
    }

    reports
        .slice()
        .sort((a, b) => new Date(b.created_at || 0) - new Date(a.created_at || 0))
        .forEach((report) => {
            const col = document.createElement("div");
            col.className = "col-12 col-md-6 col-xl-4";

            const card = document.createElement("article");
            card.className = "card report-card h-100";

            const body = document.createElement("div");
            body.className = "card-body d-flex flex-column gap-3";

            const title = document.createElement("h3");
            title.className = "h5 mb-0";
            title.textContent = report.title ?? "Untitled report";

            const summary = document.createElement("p");
            summary.className = "text-muted mb-0";
            summary.textContent = report.summary ?? "This report was generated by MetaPilot's Python analytics pipeline.";

            const meta = document.createElement("span");
            meta.className = "report-pill";
            meta.innerHTML = `<span class="bi bi-clock-history"></span><span>${formatDate(report.created_at)}</span>`;

            body.append(title, summary, meta);

            const footer = document.createElement("div");
            footer.className = "card-footer border-0 bg-transparent pt-0";

            const openButton = document.createElement("a");
            openButton.className = "btn btn-primary w-100";
            openButton.href = buildHref(report);
            openButton.target = "_blank";
            openButton.rel = "noopener";
            openButton.textContent = "Open report";
            openButton.addEventListener('click', (ev) => {
                if (openButton.href.endsWith('#')) {
                    ev.preventDefault();
                }
            });

            footer.appendChild(openButton);
            card.append(body, footer);
            col.appendChild(card);
            listContainer?.appendChild(col);
        });
};

const bootstrapManifest = (manifest) => {
    updatedAtEl && (updatedAtEl.textContent = formatDate(manifest.generated_at));
    renderReports(manifest.reports);
};

const fetchSequentially = (urls) => {
    if (!urls.length) {
        if (statusMessage) {
            statusMessage.classList.replace("alert-info", "alert-warning");
            statusMessage.textContent = "We could not find any generated reports.";
        }
        return;
    }

    const [url, ...rest] = urls;
    fetch(url, { cache: "no-store" })
        .then((response) => {
            if (!response.ok) {
                throw new Error(`Manifest not available (${response.status})`);
            }
            return response.json();
        })
        .then((manifest) => {
            // Check if manifest has reports
            if (manifest && manifest.reports && manifest.reports.length > 0) {
                bootstrapManifest(manifest);
            } else {
                // Empty manifest - show appropriate message
                if (statusMessage) {
                    statusMessage.classList.replace("alert-info", "alert-warning");
                    statusMessage.textContent = "No reports have been generated yet. Run a MetaPilot analysis to generate reports.";
                }
            }
        })
        .catch(() => {
            if (rest.length > 0) {
                fetchSequentially(rest);
            } else {
                // All URLs failed - show error message
                if (statusMessage) {
                    statusMessage.classList.replace("alert-info", "alert-warning");
                    statusMessage.textContent = "Unable to load report catalogue. Please check if reports have been generated.";
                }
            }
        });
};

if (hasInlineManifest) {
    bootstrapManifest(manifestFromWindow);
} else {
    // Set a timeout to prevent infinite loading
    const timeoutId = setTimeout(() => {
        if (statusMessage && statusMessage.textContent.includes("Loading report catalogue")) {
            statusMessage.classList.replace("alert-info", "alert-warning");
            statusMessage.textContent = "Report catalogue loading timed out. Please refresh the page or check if reports have been generated.";
        }
    }, 10000); // 10 second timeout
    
    fetchSequentially(manifestUrls);
    
    // Clear timeout if manifest loads successfully
    const originalBootstrapManifest = bootstrapManifest;
    bootstrapManifest = (manifest) => {
        clearTimeout(timeoutId);
        originalBootstrapManifest(manifest);
    };
}
